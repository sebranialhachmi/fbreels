import { AppError } from '@/lib/errors';
import type { MediaExtractor } from './media-extractor';
import type { ProviderMedia } from '@/types/media';

/**
 * TEST-ONLY PROVIDER. It does not download anything from Facebook. It returns clearly
 * labelled fixture data and "mock:" references that the download route resolves to a
 * small generated text file. It refuses to run when NODE_ENV=production (see factory).
 *
 * Deterministic scenarios keyed on the numeric video id in the URL:
 *   9990001 private/inaccessible   9990002 deleted/unavailable   9990003 no formats
 *   9990004 provider unavailable   9990005 timeout                9990006 HD+SD+audio
 *   anything else -> single SD test format
 */
export class MockExtractor implements MediaExtractor {
  readonly id = 'mock';
  readonly requiresExpandedUrl = false;

  async resolve({ url }: { url: string }): Promise<ProviderMedia> {
    const id = url.match(/(\d{5,30})/)?.[1] ?? '0';
    switch (id) {
      case '9990001':
        throw new AppError('PRIVATE_OR_INACCESSIBLE_CONTENT');
      case '9990002':
        throw new AppError('CONTENT_UNAVAILABLE');
      case '9990003':
        throw new AppError('NO_SUPPORTED_FORMATS');
      case '9990004':
        throw new AppError('PROVIDER_UNAVAILABLE');
      case '9990005':
        throw new AppError('REQUEST_TIMEOUT');
    }
    const soon = new Date(Date.now() + 10 * 60_000);
    const base = { mimeType: 'text/plain', expiresAt: soon, type: 'video' as const };
    const formats =
      id === '9990006'
        ? [
            { ...base, id: 'hd', quality: 'HD', size: 1024, upstreamUrl: `mock:${id}:hd` },
            { ...base, id: 'sd', quality: 'SD', size: 512, upstreamUrl: `mock:${id}:sd` },
            {
              ...base,
              id: 'audio',
              type: 'audio' as const,
              quality: 'Audio',
              mimeType: 'text/plain',
              size: null,
              upstreamUrl: `mock:${id}:audio`,
            },
          ]
        : [{ ...base, id: 'sd', quality: 'SD', size: 512, upstreamUrl: `mock:${id}:sd` }];
    return {
      title: `Test-only mock video ${id}`,
      thumbnail: null,
      duration: null,
      source: 'mock',
      formats,
    };
  }
}

export function mockPayload(reference: string): { body: string; mime: string } {
  return {
    mime: 'text/plain',
    body: `TEST-ONLY FILE\nGenerated by the mock extractor (${reference}).\nThis is not a Facebook video.\n`,
  };
}
